export const translate = (text, language) => language === 'fa' && Object.hasOwn(persian,text) ? persian[text] : text;

const persianDigits = '۰۱۲۳۴۵۶۷۸۹';
export const localNumber = (value,language) => language === 'fa'
  ? String(value).replace(/[0-9]/g,digit=>persianDigits[Number(digit)])
  : String(value);

export function normalizeSearch(value) {
  return value.toLowerCase().normalize('NFD')
    .replace(/[\u0300-\u036f\u064b-\u065f\u0670]/g,'')
    .replace(/[\u200c\u200d\u0640]/g,'')
    .replace(/[يى]/g,'ی').replace(/ك/g,'ک')
    .replace(/[۰-۹٠-٩]/g,digit=>String(digit.charCodeAt(0)-(digit <= '٩' ? 0x660 : 0x6f0)))
    .replace(/[’‘]/g,"'");
}
